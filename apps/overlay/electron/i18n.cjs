const dicts = { de, en };
let lang = 'de';

/** German if Windows runs in German, English otherwise. */
const systemLanguage = () => (String(app.getLocale?.() ?? '').toLowerCase().startsWith('de') ? 'de' : 'en');

function setLanguage(l) {
  lang = l === 'en' ? 'en' : 'de';
}

function t(key, vars) {
  const s = dicts[lang][key] ?? de[key] ?? key;
  return vars ? s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? '')) : s;
}

module.exports = { t, setLanguage, systemLanguage, getLanguage: () => lang };
